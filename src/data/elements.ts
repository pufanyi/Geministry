export const position = (n: number): [number, number] => {
  if (specialPositions[n]) return specialPositions[n];
  if (n <= 36) return [4, n - 18];
  if (n <= 54) return [5, n - 36];
  if (n === 55) return [6, 1];
  if (n === 56) return [6, 2];
  if (n >= 57 && n <= 71) return [9, n - 54];
  if (n >= 72 && n <= 86) return [6, n - 68];
  if (n === 87) return [7, 1];
  if (n === 88) return [7, 2];
  if (n >= 89 && n <= 103) return [10, n - 86];
  return [7, n - 100];
};
